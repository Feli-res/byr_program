import {test,expect} from '@playwright/test';
import path from 'node:path';
test.use({trace:'off'});
test.setTimeout(90000);
const enabled=process.env.E2E_ACCOUNTS==='1',failure=process.env.ACCOUNT_FAILURE_MODE==='1';
const password=process.env.ACCOUNT_TEST_PASSWORD||'';
const suffix=process.env.ACCOUNT_TEST_SUFFIX||'unused';

async function login(page,account,password){
  await page.goto('/login');await page.getByLabel('账号',{exact:true}).fill(account);await page.getByLabel('密码',{exact:true}).fill(password);
  await page.getByRole('button',{name:'登录',exact:true}).click();await expect(page).toHaveURL(/\/profile$/);
}

test('账户页面注册登录、刷新资料、头像、改密和退出',async({page})=>{
  test.skip(!enabled||failure);
  const errors=[];page.on('pageerror',e=>errors.push(e.message));
  const account='web_'+suffix;
  await page.goto('/register');
  const rules=page.locator('.account-rules');
  await expect(rules).not.toHaveAttribute('open');
  await rules.locator('summary').click();await expect(rules).toHaveAttribute('open','');
  await expect(rules).toContainText('TestUser001 与 testuser001 是两个不同的账号');
  await rules.locator('summary').press('Enter');await expect(rules).not.toHaveAttribute('open');
  await page.getByLabel('账号',{exact:true}).fill(account);await page.getByLabel('昵称',{exact:true}).fill('浏览器账户');
  await page.getByLabel('密码',{exact:true}).fill(password);await page.getByLabel('确认密码',{exact:true}).fill(password);
  await page.getByRole('button',{name:'注册账号'}).click();await expect(page.getByRole('status')).toContainText('注册成功');
  await expect(page.getByLabel('密码',{exact:true})).toHaveValue('');
  await login(page,account,password);await page.reload();await expect(page.getByRole('heading',{name:'个人资料',exact:true})).toBeVisible();
  await page.getByLabel('昵称',{exact:true}).fill('浏览器已修改');await page.getByLabel('简介',{exact:true}).fill('<script>window.injected=true</script>');
  await page.getByRole('button',{name:'保存资料'}).click();await expect(page.getByRole('status')).toContainText('已保存');
  await page.reload();await expect(page.getByLabel('昵称',{exact:true})).toHaveValue('浏览器已修改');expect(await page.evaluate(()=>window.injected)).toBeUndefined();
  // The fixture is generated by Python; it contains no user data.
  const response=await page.request.get('/health/live');expect(response.ok()).toBeTruthy();
  const fixture=process.env.ACCOUNT_PNG_FIXTURE;
  if(!fixture)throw new Error('ACCOUNT_PNG_FIXTURE must name the generated synthetic image');
  await page.getByLabel('头像',{exact:true}).setInputFiles(fixture);
  await page.getByRole('button',{name:'保存资料'}).click();await expect(page.getByAltText('当前头像')).toBeVisible();
  await page.screenshot({path:path.resolve('../../.local/logs/accounts/profile.png'),fullPage:true});
  await page.setViewportSize({width:375,height:812});expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth)).toBe(true);
  await page.screenshot({path:path.resolve('../../.local/logs/accounts/profile-mobile.png'),fullPage:true});
  await page.getByRole('link',{name:'修改密码',exact:true}).click();
  await page.getByLabel('原密码',{exact:true}).fill(password);await page.getByLabel('新密码',{exact:true}).fill(password+'N');await page.getByLabel('确认新密码',{exact:true}).fill(password+'N');
  await page.getByRole('button',{name:'修改并重新登录'}).click();await expect(page).toHaveURL(/\/login$/);
  await login(page,account,password+'N');await page.getByRole('button',{name:'退出',exact:true}).click();
  await expect(page.getByRole('heading',{name:'请先登录',exact:true})).toBeVisible();
  expect(errors).toEqual([]);
});

test('管理员签发重置凭据、普通用户界面不能管理账户',async({browser})=>{
  test.skip(!enabled||failure);
  const member=await browser.newContext();const person=await member.newPage();const account='reset_'+suffix;
  await person.goto('/register');await person.getByLabel('账号',{exact:true}).fill(account);await person.getByLabel('昵称',{exact:true}).fill('浏览器重置对象');
  await person.getByLabel('密码',{exact:true}).fill(password);await person.getByLabel('确认密码',{exact:true}).fill(password);await person.getByRole('button',{name:'注册账号'}).click();await expect(person.getByRole('status')).toContainText('注册成功');
  await login(person,account,password);
  await person.goto('/admin/users');await expect(person.getByRole('heading',{name:'没有访问权限'})).toBeVisible();
  const manager=await browser.newContext();const page=await manager.newPage();await login(page,process.env.ACCOUNT_ADMIN,process.env.ACCOUNT_ADMIN_PASSWORD);
  await page.getByRole('link',{name:'账户管理',exact:true}).click();
  const row=page.locator('.managed-user').filter({has:page.getByRole('heading',{name:/浏览器重置对象/})});await expect(row).toBeVisible();
  const other=page.locator('.managed-user').first(),rowToggle=row.locator('.managed-toggle'),otherToggle=other.locator('.managed-toggle');
  await expect(rowToggle).toHaveAttribute('aria-expanded','false');await expect(row).toContainText(account);await expect(row.getByLabel('操作原因',{exact:true})).toBeHidden();
  await rowToggle.click();await otherToggle.click();await expect(rowToggle).toHaveAttribute('aria-expanded','true');await expect(otherToggle).toHaveAttribute('aria-expanded','true');
  await page.getByLabel('单项展开').check();await expect(rowToggle).toHaveAttribute('aria-expanded','false');await expect(otherToggle).toHaveAttribute('aria-expanded','true');
  await rowToggle.click();await expect(otherToggle).toHaveAttribute('aria-expanded','false');await expect(rowToggle).toHaveAttribute('aria-expanded','true');
  await row.getByLabel('操作原因',{exact:true}).fill('浏览器核实后重置检查');
  page.once('dialog',dialog=>dialog.accept());await row.getByRole('button',{name:'签发重置凭据'}).click();
  const credential=await row.getByLabel('重置凭据',{exact:true}).inputValue();expect(credential.length).toBeGreaterThan(31);
  await rowToggle.click();await expect(row.getByLabel('重置凭据',{exact:true})).toBeHidden();await rowToggle.click();await expect(row.getByLabel('重置凭据',{exact:true})).toHaveValue(credential);
  await person.goto('/profile');await expect(person.getByRole('heading',{name:'请先登录',exact:true})).toBeVisible();
  await person.goto('/reset-password');await person.getByLabel('一次性重置凭据',{exact:true}).fill(credential);
  await person.getByLabel('新密码',{exact:true}).fill(password+'R');await person.getByLabel('确认新密码',{exact:true}).fill(password+'R');await person.getByRole('button',{name:'重置密码',exact:true}).click();
  await expect(person.getByRole('status')).toContainText('密码已重置');await login(person,account,password+'R');
  // Never screenshot a visible reset credential.
  await row.getByRole('button',{name:'关闭凭据显示'}).click();await page.screenshot({path:path.resolve('../../.local/logs/accounts/admin.png'),fullPage:true});
  await member.close();await manager.close();
});

test('真实数据库故障时注册失败、保留账号昵称并清空密码',async({page})=>{
  test.skip(!enabled||!failure);
  const account='fault_'+suffix;
  await page.goto('/register');await page.getByLabel('账号',{exact:true}).fill(account);await page.getByLabel('昵称',{exact:true}).fill('故障时保留昵称');
  await page.getByLabel('密码',{exact:true}).fill(password);await page.getByLabel('确认密码',{exact:true}).fill(password);
  await page.getByRole('button',{name:'注册账号'}).click();await expect(page.getByRole('alert').filter({hasText:'服务暂时不可用'})).toBeVisible({timeout:20000});
  await expect(page.getByLabel('账号',{exact:true})).toHaveValue(account);await expect(page.getByLabel('昵称',{exact:true})).toHaveValue('故障时保留昵称');
  await expect(page.getByLabel('密码',{exact:true})).toHaveValue('');await expect(page.getByRole('status')).toHaveCount(0);
  await page.screenshot({path:path.resolve('../../.local/logs/accounts/database-failure.png'),fullPage:true});
});
